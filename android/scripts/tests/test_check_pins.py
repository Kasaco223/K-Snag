"""Prueba check_pins.py sin red. Uso: python3 -I -X utf8 test_check_pins.py <check_pins.py>"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

script = sys.argv[1]
SHA, OTHER = "a" * 64, "b" * 64
PINS = {"io.github.junkfood02.youtubedl-android:library:0.18.1": {"aar_sha256": SHA, "aar_size": 1}}


def meta(sha, verify="true"):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
  <configuration><verify-metadata>{verify}</verify-metadata></configuration>
  <components>
    <component group="io.github.junkfood02.youtubedl-android" name="library" version="0.18.1">
      <artifact name="library-0.18.1.aar"><sha256 value="{sha}" origin="Generated by Gradle"/></artifact>
    </component>
  </components>
</verification-metadata>
"""


CAT = '[versions]\nyoutubedl = "0.18.1"\n\n[libraries]\nyoutubedl-library = { module = "io.github.junkfood02.youtubedl-android:library", version.ref = "youtubedl" }\n'


def case(name, want, catalog=CAT, metadata=meta(SHA), pins=PINS):
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        (root / "android/third_party").mkdir(parents=True)
        (root / "android/gradle").mkdir(parents=True)
        (root / "android/gradle/libs.versions.toml").write_text(catalog, encoding="utf-8")
        (root / "android/third_party/components.json").write_text(json.dumps(
            {"schema": 1, "components": [{"id": "youtubedl-android", "maven": pins}]}), encoding="utf-8")
        if metadata is not None:
            (root / "android/gradle/verification-metadata.xml").write_text(metadata, encoding="utf-8")
        e = dict(os.environ, KD_ROOT=str(root), PYTHONIOENCODING="utf-8")
        r = subprocess.run([sys.executable, "-I", "-X", "utf8", script], env=e, capture_output=True, text=True)
        ok = r.returncode == want
        print(("OK  " if ok else "FAIL"), name)
        if not ok:
            print(r.stdout, r.stderr)
        return ok


results = [
    case("sin youtubedl en el catálogo: no hay nada que cruzar", 0, catalog='coil = "3.6.3"\n', metadata=None),
    case("SHA-256 igual en Gradle y en components.json", 0),
    case("SHA-256 distinto", 1, metadata=meta(OTHER)),
    case("falta verification-metadata.xml", 1, metadata=None),
    case("verify-metadata en false", 1, metadata=meta(SHA, "false")),
    case("el catálogo usa otra versión", 1, catalog=CAT.replace("0.18.1", "0.19.0")),
    case("clave camelCase con version.ref", 0, catalog=CAT.replace("youtubedl =", "ytdlAndroid =").replace('"youtubedl" }', '"ytdlAndroid" }')),
    case("nombrado sin versión que se pueda resolver", 1, catalog=CAT.replace('version.ref = "youtubedl"', 'version.ref = "nada"')),
    case("components.json sin pins", 1, pins={}),
]
print(f"{sum(results)}/{len(results)} casos OK")
sys.exit(0 if all(results) else 1)
